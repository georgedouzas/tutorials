#!/usr/bin/env python3
"""Content checker for the tutorials (openspec/changes/maths-physicists-content, design M4; software profiles from
openspec/changes/complexity-and-system-design-tutorials, design C3-C5).

Usage:
  python3 _filters/check_content.py <tutorial> [<chapter> ...] [<tutorial> [<chapter> ...] ...]
                                    [--run | --sage] [--update] [--figures] [--backlog] [--as-raised]
  python3 _filters/check_content.py --site-captions

Software profile: <tutorial>/_software.yml names the tutorial's software. Without it the tutorial has the SageMath
profile below, and the checker behaves exactly as before profiles existed. The file is a small YAML subset (read
without PyYAML): "key: value", "key: [a, b]" or a "- item" list, and one nested mapping for runner:

  tab: Python                       # label of the second solution tab                     (SageMath)
  first_tabs: [Proof, Solution]     # accepted labels of the first tab                     ([Proof])
  language: Python                  # name used in findings                                (Sage)
  fence: "{.python .run}"           # code block classes; the last class marks a run block ({.python .sage})
  output_fence: "{.text .run-output}"  # recorded-output block; its last class marks it     ({.text .sage-output})
  runner:
    kind: python                    # python: plain exec; sage: Sage preparser and forget() (sage)
    command: .venv-complexity/bin/python   # a path relative to the project root, or a command on PATH (sage -python)
    timeout: 120                    # seconds per block                                     (120)
  figure_kinds: [py, d2]            # accepted figure scripts: sage, py, d2                 ([sage])
  illustrative: "{.code .illustrative}"  # code that is shown, never run; its last class marks it (none)

For each chapter of <tutorial> (all chapters if none are named) it checks:
  * counts: in a chapter listed in <tutorial>/_raised.txt, every def-/thm-/lem-/prp-/cor- block is followed by at
    exactly ten exm- and ten exr- blocks before the next statement (or the closing "## Exercises" section), unless the
    statement is listed as an exception; other chapters need three (reported only with --backlog);
  * solutions (raised chapters): every .solution callout holds a panel-tabset with two tabs, a first tab from
    first_tabs ("Proof") then the profile's tab ("SageMath"), and that tab has a code block (```{.python .sage})
    followed by an output block (```{.text .sage-output}); an illustrative block followed by an output block is
    reported;
  * code outputs (--run, or its alias --sage, raised chapters): every code block followed by an output block, in
    solutions and examples alike, is run with the profile's runner (one process per chapter, a fresh namespace and a
    timeout per block) and its printed output compared with the recorded one; a block that prints nothing is
    reported; --update writes the new output into the page instead. Illustrative blocks are never run. If the runner
    is missing, "<tutorial>: not checked (environment missing)" is printed and the other checks go on;
  * figures (raised chapters): every image and interactive figure the chapter uses has a figures/<stem>.<kind>
    script of a kind in figure_kinds; a .d2 source starts by importing _filters/d2-theme. --figures runs each script
    (sage: "sage"; py: the runner, with _filters/figstyle.py; d2: the pinned D2, "d2 --layout=elk --pad=16
    figures/<stem>.d2 figures/<stem>.svg") and checks that it writes the files the chapter references;
  * captions (every chapter): no "Generated by", no .sage/.py/.d2 file names, no tool names (Sage/SageMath, Plotly,
    matplotlib, threejs, Python, NumPy, SciPy, SimPy, NetworkX, Mesa, powerlaw, scikit-complexity, D2), at most two
    sentences;
  * forward references (every chapter): no @label may point to something defined later in the tutorial, later in
    the same chapter or in a later chapter of the sidebar order. Links to other tutorials are allowed, and so is
    the chapter introduction's list of the chapter's own sections, and a figure, equation or table named a few lines
    before it appears. Findings in raised chapters; elsewhere counted with --backlog.

Several tutorials may be named in one run; an argument that names a folder of the project (and not a chapter of the
tutorial before it) starts a new tutorial.
--as-raised: treat the chapters named on the command line as raised (for work in progress; _raised.txt untouched).
_raised.txt: one chapter slug per line; "<chapter> <label> <reason>" records a statement exception (minimum three);
"#" starts a comment. Exits 1 if anything is reported (backlog and "not checked" lines do not count).
"""
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TUTORIALS = ["fundamentals-of-mathematics-for-physicists", "fundamentals-of-theoretical-physics",
             "kaluza-klein-theories", "fundamentals-of-mathematics-for-machine-learning",
             "fundamentals-of-machine-learning", "complexity-science", "system-design"]
STATEMENT = re.compile(r"^:::+ *\{#(def|thm|lem|prp|cor)-([A-Za-z0-9_-]+)")
ITEM = re.compile(r"^:::+ *\{#(exm|exr)-")
DIV_OPEN = re.compile(r"^(:::+) *\S")
DIV_CLOSE = re.compile(r"^:::+\s*$")
FENCE = re.compile(r"^(`{3,})(.*)$", re.M)
CLOSING_SECTION = re.compile(r"^## Exercises\b")
SAGE_TIMEOUT = 120
D2_VERSION = "v0.9.0"
D2_THEME_IMPORT = re.compile(r"^\s*\.\.\.@(\.\./)+_filters/d2-theme(\.d2)?\s*$", re.M)


# ---------------------------------------------------------------------------------------------------- profiles
SAGE_PROFILE = {
    "tab": "SageMath",
    "first_tabs": ["Proof"],
    "language": "Sage",
    "fence": "{.python .sage}",
    "output_fence": "{.text .sage-output}",
    "runner": {"kind": "sage", "command": "sage -python", "timeout": SAGE_TIMEOUT},
    "figure_kinds": ["sage"],
    "illustrative": None,
}
FIGURE_KINDS = ("sage", "py", "d2")


def _scalar(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    if v.startswith("[") and v.endswith("]"):
        return [_scalar(x) for x in v[1:-1].split(",") if x.strip()]
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    if v in ("null", "~", ""):
        return None
    return v


def parse_profile(text):
    """The YAML subset of _software.yml: top-level "key: value", "key: [a, b]", a "- item" list, or one level of
    nested "sub: value" mapping."""
    out, key = {}, None
    for raw in text.split("\n"):
        line = re.sub(r"(^|\s)#.*$", "", raw).rstrip()
        if not line.strip():
            continue
        indented = line[0] in " \t"
        s = line.strip()
        if not indented:
            k, _, v = s.partition(":")
            key = k.strip()
            out[key] = _scalar(v) if v.strip() else None
        elif key is not None and s.startswith("- "):
            if not isinstance(out[key], list):
                out[key] = []
            out[key].append(_scalar(s[2:]))
        elif key is not None and ":" in s:
            if not isinstance(out[key], dict):
                out[key] = {}
            k, _, v = s.partition(":")
            out[key][k.strip()] = _scalar(v)
    return out


def last_class(fence):
    """The marking class of a fence spec such as "{.python .run}" (here "run"), or None."""
    classes = re.findall(r"\.([\w-]+)", fence or "")
    return classes[-1] if classes else None


def load_profile(tut):
    """The tutorial's profile: _software.yml over the SageMath defaults, with derived fields."""
    p = {k: (dict(v) if isinstance(v, dict) else v) for k, v in SAGE_PROFILE.items()}
    path = os.path.join(ROOT, tut, "_software.yml")
    if os.path.exists(path):
        given = parse_profile(open(path, encoding="utf-8").read())
        runner = given.pop("runner", None)
        p.update({k: v for k, v in given.items() if v is not None})
        if isinstance(runner, str):
            runner = {"command": runner}
        if isinstance(runner, dict):
            p["runner"] = {"kind": "python", "command": "", "timeout": SAGE_TIMEOUT, **runner}
        if isinstance(p["first_tabs"], str):
            p["first_tabs"] = [p["first_tabs"]]
        if isinstance(p["figure_kinds"], str):
            p["figure_kinds"] = [p["figure_kinds"]]
        bad = [k for k in p["figure_kinds"] if k not in FIGURE_KINDS]
        if bad:
            sys.exit(f"{tut}/_software.yml: unknown figure kinds {bad} (use {', '.join(FIGURE_KINDS)})")
    p["run_class"] = last_class(p["fence"])
    p["output_class"] = last_class(p["output_fence"])
    p["illustrative_class"] = last_class(p["illustrative"]) if p["illustrative"] else None
    return p


def runner_command(p):
    """The runner's argv with its executable resolved (a path is relative to the project root), or None if the
    environment is missing."""
    argv = shlex.split(str(p["runner"]["command"]))
    if not argv:
        return None
    exe = argv[0]
    if "/" in exe:
        exe = exe if os.path.isabs(exe) else os.path.join(ROOT, exe)
        if not (os.path.isfile(exe) and os.access(exe, os.X_OK)):
            return None
    elif shutil.which(exe) is None:
        return None
    return [exe] + argv[1:]


def d2_command():
    """The pinned D2 binary, or None if it is missing or another version."""
    exe = shutil.which("d2") or ("/opt/homebrew/bin/d2" if os.path.exists("/opt/homebrew/bin/d2") else None)
    if exe is None:
        return None
    try:
        version = subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    return exe if version == D2_VERSION else None


def read_raised(tut):
    chapters, exceptions = set(), {}
    path = os.path.join(ROOT, tut, "_raised.txt")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split(None, 2)
            if len(parts) == 1:
                chapters.add(parts[0])
            else:
                exceptions[(parts[0], parts[1])] = parts[2] if len(parts) > 2 else ""
    return chapters, exceptions


def chapters_of(tut):
    d = os.path.join(ROOT, tut)
    return sorted(c for c in os.listdir(d) if os.path.isfile(os.path.join(d, c, "index.qmd")))


def code_mask(lines):
    """True for lines inside (or delimiting) a fenced code block."""
    mask, fence = [], None
    for l in lines:
        m = FENCE.match(l)
        if fence is None and m:
            fence = m.group(1)
            mask.append(True)
        elif fence is not None:
            mask.append(True)
            if l.strip() == fence:
                fence = None
        else:
            mask.append(False)
    return mask


def divs(lines, mask):
    """List of (start, end, header) for every fenced div; end is the index of its closing line."""
    out, stack = [], []
    for i, l in enumerate(lines):
        if mask[i]:
            continue
        if DIV_CLOSE.match(l):
            if stack:
                s = stack.pop()
                out.append((s, i, lines[s]))
        elif DIV_OPEN.match(l):
            stack.append(i)
    return out


# ---------------------------------------------------------------------------------------------------- counts
def check_counts(lines, mask, minimum, exceptions, chapter):
    findings, backlog = [], []
    stats, cur = [], None
    for i, l in enumerate(lines):
        if mask[i]:
            continue
        if CLOSING_SECTION.match(l):
            cur = None
            continue
        m = STATEMENT.match(l)
        if m:
            cur = {"label": f"{m.group(1)}-{m.group(2)}", "line": i + 1, "exm": 0, "exr": 0}
            stats.append(cur)
            continue
        m = ITEM.match(l)
        if m and cur is not None:
            cur[m.group(1)] += 1
    for s in stats:
        if (chapter, s["label"]) in exceptions:
            bad = s["exm"] < 3 or s["exr"] < 3 or s["exm"] > 10 or s["exr"] > 10
            need = "3 to 10 (exception)"
        elif minimum == 10:
            bad = s["exm"] != 10 or s["exr"] != 10
            need = "exactly 10"
        else:
            bad = s["exm"] < minimum or s["exr"] < minimum
            need = f"at least {minimum}"
        if bad:
            findings.append(f"{s['line']}: {s['label']} has {s['exm']} examples and {s['exr']} exercises (needs {need})")
        lack_e, lack_x = max(0, 10 - s["exm"]), max(0, 10 - s["exr"])
        if lack_e or lack_x:
            backlog.append((s["label"], lack_e, lack_x))
    return findings, backlog, stats


# ---------------------------------------------------------------------------------------------------- solutions
def tabs_in(lines, start, end):
    """The '## ' tab headings between start and end that are not inside code."""
    return [(i, lines[i][3:].strip()) for i in range(start + 1, end) if lines[i].startswith("## ")]


def expected_tabs(p):
    first = p["first_tabs"]
    if len(first) == 1:
        return str([first[0], p["tab"]])
    return "[" + " or ".join(repr(t) for t in first) + f", {p['tab']!r}]"


def check_solutions(lines, mask, alldivs, p=SAGE_PROFILE):
    findings = []
    first, tab = p["first_tabs"], p["tab"]
    for s, e, h in alldivs:
        if not re.search(r"\.solution(?![\w-])", h):
            continue
        inner = [d for d in alldivs if s < d[0] and d[1] < e and "panel-tabset" in d[2]]
        if not inner:
            findings.append(f"{s + 1}: solution has no {' or '.join(first)}/{tab} tabs")
            continue
        ts, te, _ = inner[0]
        tabs = [t for i, t in tabs_in(lines, ts, te) if not mask[i]]
        if len(tabs) != 2 or tabs[0] not in first or tabs[1] != tab:
            findings.append(f"{s + 1}: solution tabs are {tabs}, expected {expected_tabs(p)}")
            continue
        code_start = [i for i, t in tabs_in(lines, ts, te) if t == tab][0]
        body = "\n".join(lines[code_start:te])
        if (not any(is_code_fence(f.group(2), p) for f in FENCE.finditer(body))
                or f".{p['output_class']}" not in body):
            findings.append(f"{s + 1}: {tab} tab lacks a ```{p['run_class']} block followed by a "
                            f"{p['output_class']} block")
    return findings


# ---------------------------------------------------------------------------------------------------- code blocks
def has_class(info, cls):
    """A fence such as ```{.python .sage} carries the class cls (```sage, the bare name, counts too)."""
    info = info.strip()
    return info == cls or bool(re.fullmatch(r"\{[^}]*\." + re.escape(cls) + r"(\s[^}]*)?\}", info))


def is_code_fence(info, p=SAGE_PROFILE):
    """A run block of the profile: ```{.python .sage} or ```sage for SageMath, ```{.python .run} for Python. A block
    with the illustrative class is never one."""
    if p.get("illustrative_class") and has_class(info, p["illustrative_class"]):
        return False
    return has_class(info, p["run_class"])


def is_sage_fence(info):
    """A Sage code fence: ```{.python .sage} (highlighted as Python) or ```sage."""
    return is_code_fence(info, SAGE_PROFILE)


def fence_end(lines, i):
    """Index of the closing fence of the block opened at line i (len(lines) if unclosed)."""
    fence = FENCE.match(lines[i]).group(1)
    j = i + 1
    while j < len(lines) and lines[j].strip() != fence:
        j += 1
    return j


def next_fence(lines, j):
    """The FENCE match of the first non-blank line after j, and its index."""
    k = j + 1
    while k < len(lines) and not lines[k].strip():
        k += 1
    return (FENCE.match(lines[k]) if k < len(lines) else None), k


def code_pairs(lines, p=SAGE_PROFILE):
    """(code_start, code_end, out_start, out_end) index ranges (exclusive of fences) of code/output pairs."""
    pairs, i, n = [], 0, len(lines)
    out_mark = "." + p["output_class"]
    while i < n:
        m = FENCE.match(lines[i])
        if m and is_code_fence(m.group(2), p):
            j = fence_end(lines, i)
            mo, k = next_fence(lines, j)
            if mo and out_mark in mo.group(2):
                l2 = fence_end(lines, k)
                pairs.append((i + 1, j, k + 1, l2))
                i = l2 + 1
                continue
            i = j + 1
            continue
        if m:  # skip other code blocks whole
            i = fence_end(lines, i)
        i += 1
    return pairs


def sage_pairs(lines):
    return code_pairs(lines, SAGE_PROFILE)


def check_illustrative(lines, p):
    """An illustrative block is shown, not run, so it must not carry a recorded-output block."""
    if not p.get("illustrative_class"):
        return []
    findings, i, n = [], 0, len(lines)
    out_mark = "." + p["output_class"]
    while i < n:
        m = FENCE.match(lines[i])
        if not m:
            i += 1
            continue
        j = fence_end(lines, i)
        if has_class(m.group(2), p["illustrative_class"]):
            mo, _ = next_fence(lines, j)
            if mo and out_mark in mo.group(2):
                findings.append(f"{i + 1}: illustrative block is followed by a {p['output_class']} block")
        i = j + 1
    return findings


RUNNER = r'''
import sys, io, json, signal, contextlib, traceback
from sage.all import *
from sage.repl.preparse import preparse
base = dict(globals())
blocks = json.load(open(sys.argv[1]))
results = []
def _timeout(*a):
    raise TimeoutError("block timed out")
signal.signal(signal.SIGALRM, _timeout)
for code in blocks:
    ns = dict(base)
    forget()  # assumptions are global to the Sage process, not to the namespace
    buf = io.StringIO()
    signal.alarm(%d)
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(preparse(code), "<sage block>", "exec"), ns)
        results.append({"ok": True, "out": buf.getvalue()})
    except BaseException:
        results.append({"ok": False, "out": buf.getvalue(), "err": traceback.format_exc(limit=3)})
    finally:
        signal.alarm(0)
json.dump(results, open(sys.argv[2], "w"))
'''

PYTHON_RUNNER = r'''
import sys, io, json, os, signal, contextlib, traceback
os.environ.setdefault("MPLBACKEND", "Agg")
blocks = json.load(open(sys.argv[1]))
results = []
def _timeout(*a):
    raise TimeoutError("block timed out")
signal.signal(signal.SIGALRM, _timeout)
for code in blocks:
    ns = {"__name__": "__main__", "__builtins__": __builtins__}
    buf = io.StringIO()
    signal.alarm(%d)
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(code, "<python block>", "exec"), ns)
        results.append({"ok": True, "out": buf.getvalue()})
    except BaseException:
        results.append({"ok": False, "out": buf.getvalue(), "err": traceback.format_exc(limit=3)})
    finally:
        signal.alarm(0)
json.dump(results, open(sys.argv[2], "w"))
'''


def norm(text):
    return "\n".join(l.rstrip() for l in text.strip("\n").split("\n")).strip("\n")


def run_blocks(blocks, p, argv):
    """Run each block in a fresh namespace in one process of the profile's runner; [{ok, out, err}]."""
    import json
    template = RUNNER if p["runner"].get("kind") == "sage" else PYTHON_RUNNER
    with tempfile.TemporaryDirectory() as tmp:
        src, out, runner = (os.path.join(tmp, n) for n in ("in.json", "out.json", "runner.py"))
        json.dump(blocks, open(src, "w"))
        open(runner, "w").write(template % int(p["runner"].get("timeout") or SAGE_TIMEOUT))
        env = dict(os.environ, MPLBACKEND="Agg") if template is PYTHON_RUNNER else None
        subprocess.run(argv + [runner, src, out], check=True, cwd=tmp, env=env)
        return json.load(open(out))


def run_sage(blocks):
    return run_blocks(blocks, SAGE_PROFILE, ["sage", "-python"])


def check_code(path, lines, update, p, argv):
    pairs = code_pairs(lines, p)
    if not pairs:
        return [], False
    results = run_blocks(["\n".join(lines[a:b]) for a, b, _, _ in pairs], p, argv)
    lang = p["language"]
    findings, changed = [], False
    for (a, b, c, d), r in reversed(list(zip(pairs, results))):
        if not r["ok"]:
            findings.append(f"{a}: {lang} block fails: {r['err'].strip().splitlines()[-1]}")
            continue
        got, shown = norm(r["out"]), norm("\n".join(lines[c:d]))
        if not got:  # every block prints its result; silence means a Maxima question or a lost print
            findings.append(f"{a}: {lang} block prints nothing")
            continue
        if got != shown:
            if update:
                lines[c:d] = got.split("\n") if got else []
                changed = True
            else:
                findings.append(f"{a}: {lang} output differs from the recorded output")
    if changed:
        open(path, "w", encoding="utf-8").write("\n".join(lines))  # lines came from text.split("\n")
    return sorted(findings, key=lambda f: int(f.split(":")[0])), changed


def check_sage(path, lines, update):
    return check_code(path, lines, update, SAGE_PROFILE, ["sage", "-python"])


# ---------------------------------------------------------------------------------------------------- figures
IMAGE = re.compile(r"\]\((figures/[^)\s]+)\)")
INTERACTIVE = re.compile(r"\{\{< *interactive +([A-Za-z0-9_-]+)")


def figure_refs(text):
    refs = set(IMAGE.findall(text))
    refs |= {f"figures/interactive/{n}.html" for n in INTERACTIVE.findall(text)}
    return sorted(refs)


def script_for(chdir, ref, kinds=("sage",)):
    """The figure's script figures/<stem>.<kind>, for the first kind that exists (else the first kind's path)."""
    stem = os.path.splitext(os.path.basename(ref))[0]
    paths = [os.path.join(chdir, "figures", f"{stem}.{k}") for k in kinds]
    return next((s for s in paths if os.path.exists(s)), paths[0])


class Tools:
    """What --run and --figures need for one tutorial, resolved once; prints each "not checked" notice once."""

    def __init__(self, tut, p):
        self.tut, self.p = tut, p
        self.argv = runner_command(p)
        self._d2 = None
        self.told = set()

    def notice(self, what):
        if what not in self.told:
            self.told.add(what)
            print(f"{self.tut}: {what}")

    def runner(self):
        if self.argv is None:
            self.notice("not checked (environment missing)")
        return self.argv

    def d2(self):
        if self._d2 is None:
            self._d2 = d2_command() or ""
        if not self._d2:
            self.notice(f"diagrams not rendered (D2 {D2_VERSION} missing)")
        return self._d2 or None


def figure_command(script, tools):
    """The command that runs a figure script from the chapter folder, or None if its tool is missing."""
    rel = os.path.join("figures", os.path.basename(script))
    kind = os.path.splitext(script)[1][1:]
    if kind == "sage":
        return ["sage", script]
    if kind == "py":
        argv = tools.runner()
        return argv + [rel] if argv else None
    if kind == "d2":
        d2 = tools.d2()
        return [d2, "--layout=elk", "--pad=16", rel, os.path.splitext(rel)[0] + ".svg"] if d2 else None
    return None


def check_figures(chdir, text, run, p=SAGE_PROFILE, tools=None):
    findings = []
    kinds = p["figure_kinds"]
    for ref in figure_refs(text):
        script = script_for(chdir, ref, kinds)
        name = os.path.basename(script)
        if not os.path.exists(script):
            if len(kinds) == 1:
                findings.append(f"{ref}: no generating script figures/{name}")
            else:
                stem = os.path.splitext(name)[0]
                findings.append(f"{ref}: no generating script ({' or '.join(f'figures/{stem}.{k}' for k in kinds)})")
            continue
        if script.endswith(".d2") and not D2_THEME_IMPORT.search(open(script, encoding="utf-8").read()):
            findings.append(f"{ref}: figures/{name} does not import _filters/d2-theme")
        if run:
            cmd = figure_command(script, tools) if tools else ["sage", script]
            if cmd is None:
                continue
            target = os.path.join(chdir, ref)
            before = os.path.getmtime(target) if os.path.exists(target) else 0
            env = dict(os.environ, MPLBACKEND="Agg") if script.endswith(".py") else None
            p_ = subprocess.run(cmd, cwd=chdir, capture_output=True, text=True, timeout=900, env=env)
            if p_.returncode:
                findings.append(f"{ref}: figures/{name} failed: {p_.stderr.strip()[-300:]}")
            elif not os.path.exists(target) or os.path.getmtime(target) <= before:
                findings.append(f"{ref}: figures/{name} did not write it")
            elif script.endswith(".d2"):
                os.chmod(target, 0o644)  # d2 writes 0600; the site and git expect world-readable figures
    return findings


# ---------------------------------------------------------------------------------------------------- captions
def captions(text):
    """(line, caption) for every image ![caption](...). Brackets inside $...$ math (a half-open interval such as
    [0, 2\\pi)) do not count when matching the caption's closing bracket."""
    out, i = [], 0
    while True:
        i = text.find("![", i)
        if i < 0:
            return out
        depth, j, math = 1, i + 2, False
        while j < len(text) and depth:
            ch = text[j]
            if ch == "$" and text[j - 1] != "\\":
                math = not math
            elif not math:
                depth += {"[": 1, "]": -1}.get(ch, 0)
            j += 1
        if text[j:j + 1] == "(":
            out.append((text.count("\n", 0, i) + 1, text[i + 2:j - 1]))
        i = j


TOOL_NAMES = re.compile(r"\bSage\w*|\bPlotly\b|\bmatplotlib\b|\bthreejs\b|\bPython\b|\bNumPy\b|\bSciPy\b|\bSimPy\b"
                        r"|\bNetworkX\b|\bMesa\b|\bpowerlaw\b|\bscikit-complexity\b|\bskcomplex\b", re.I)


def caption_findings(text):
    findings = []
    for line, cap in captions(text):
        plain = re.sub(r"\$[^$]*\$", "x", cap)
        plain = re.sub(r"`[^`]*`", "x", plain)
        problems = []
        if re.search(r"Generated by", cap):
            problems.append('says "Generated by"')
        if re.search(r"\.(sage|py|d2)\b", cap):
            problems.append("names a script")
        if TOOL_NAMES.search(plain) or re.search(r"\bD2\b", plain):
            problems.append("mentions a tool")
        sentences = len(re.findall(r"[.!?](?=\s+[A-Z(]|\s*$)", plain.strip()))
        if sentences > 2:
            problems.append(f"has {sentences} sentences")
        if problems:
            findings.append(f"{line}: caption {', '.join(problems)}")
    return findings


# ---------------------------------------------------------------------------------------------------- forward references
LABEL = re.compile(r"\{#((?:sec|def|thm|lem|prp|cor|exm|exr|eq|fig|tbl|rem)-[A-Za-z0-9_-]+)")
REF = re.compile(r"(?<![\w@])-?@((?:sec|def|thm|lem|prp|cor|exm|exr|eq|fig|tbl|rem)-[A-Za-z0-9_-]*[A-Za-z0-9])")


NEAR = 30  # a figure, equation or table may be named up to this many lines before it appears


def sidebar_order(tut):
    order = []
    for line in open(os.path.join(ROOT, "_quarto.yml"), encoding="utf-8"):
        m = re.search(re.escape(tut) + r"/([A-Za-z0-9_-]+)/index\.qmd", line)
        if m and m.group(1) not in order:
            order.append(m.group(1))
    return order


def label_positions(tut):
    """label -> (chapter rank, line index) over the tutorial's chapters in sidebar order."""
    pos = {}
    for rank, ch in enumerate(sidebar_order(tut)):
        path = os.path.join(ROOT, tut, ch, "index.qmd")
        if not os.path.exists(path):
            continue
        lines = open(path, encoding="utf-8").read().split("\n")
        mask = code_mask(lines)
        for i, l in enumerate(lines):
            if not mask[i]:
                for m in LABEL.finditer(l):
                    pos.setdefault(m.group(1), (rank, i))
    return pos


def check_forward(tut, ch, lines, mask, pos):
    order = sidebar_order(tut)
    if ch not in order or ch == "glossary":
        return []
    rank = order.index(ch)
    first_section = next((i for i, l in enumerate(lines) if l.startswith("## ") and not mask[i]), len(lines))
    out = []
    for i, l in enumerate(lines):
        if mask[i]:
            continue
        for m in REF.finditer(l):
            lab = m.group(1)
            if lab not in pos:
                continue
            r, j = pos[lab]
            if r < rank or (r == rank and j <= i):
                continue
            if r == rank and i < first_section and lab.startswith("sec-"):
                continue
            if r == rank and lab.split("-")[0] in ("fig", "eq", "tbl") and j - i <= NEAR:
                continue
            where = "later in this chapter" if r == rank else f"in the later chapter {order[r]}"
            out.append(f"{i + 1}: forward reference @{lab}, defined {where}")
    return out


# ---------------------------------------------------------------------------------------------------- main
def tutorial_groups(args):
    """[(tutorial, [chapter, ...]), ...]: an argument that names a project folder, and not a chapter of the tutorial
    before it, starts a new tutorial."""
    groups = []
    for a in args:
        if groups:
            tut = groups[-1][0]
            is_chapter = os.path.isfile(os.path.join(ROOT, tut, a, "index.qmd"))
            if is_chapter or not os.path.isdir(os.path.join(ROOT, a.rstrip("/"))):
                groups[-1][1].append(a)
                continue
        groups.append((a.rstrip("/"), []))
    return groups


def check_tutorial(tut, named, flags):
    """Check one tutorial; prints its findings and returns (findings, backlog examples, backlog exercises)."""
    total = 0
    p = load_profile(tut)
    tools = Tools(tut, p)
    run = "--run" in flags or "--sage" in flags or "--update" in flags
    raised, exceptions = read_raised(tut)
    chapters = named or chapters_of(tut)
    if "--as-raised" in flags:  # treat the named chapters as raised without editing _raised.txt
        raised = raised | set(named)
    backlog_total = [0, 0]
    pos = label_positions(tut)
    for ch in chapters:
        chdir = os.path.join(ROOT, tut, ch)
        path = os.path.join(chdir, "index.qmd")
        text = open(path, encoding="utf-8").read()
        lines = text.split("\n")
        mask = code_mask(lines)
        is_raised = ch in raised
        findings = []
        fwd = check_forward(tut, ch, lines, mask, pos)  # before --update, which rewrites lines
        if is_raised:
            findings += fwd
        f, backlog, stats = check_counts(lines, mask, 10 if is_raised else 3, exceptions, ch)
        findings += f
        if is_raised:
            findings += check_solutions(lines, mask, divs(lines, mask), p)
            findings += check_illustrative(lines, p)
            findings += check_figures(chdir, text, "--figures" in flags, p, tools)
            if run and code_pairs(lines, p):
                argv = tools.runner()
                if argv is not None:
                    f, _ = check_code(path, lines, "--update" in flags, p, argv)
                    findings += f
        findings += caption_findings(text)
        for f in findings:
            print(f"{tut}/{ch}/index.qmd:{f}")
        total += len(findings)
        if "--backlog" in flags and stats:
            e, x = sum(b[1] for b in backlog), sum(b[2] for b in backlog)
            backlog_total[0] += e
            backlog_total[1] += x
            print(f"  backlog {ch}{' (raised)' if is_raised else ''}: {len(stats)} statements, "
                  f"{e} examples and {x} exercises missing for ten, {len(fwd)} forward references")
    return total, backlog_total


def main(argv):
    flags = {a for a in argv if a.startswith("--")}
    args = [a for a in argv if not a.startswith("--")]
    total = 0
    if "--site-captions" in flags:
        for tut in TUTORIALS:
            if not os.path.isdir(os.path.join(ROOT, tut)):
                continue
            for ch in chapters_of(tut):
                text = open(os.path.join(ROOT, tut, ch, "index.qmd"), encoding="utf-8").read()
                for f in caption_findings(text):
                    print(f"{tut}/{ch}/index.qmd:{f}")
                    total += 1
        print(f"{total} caption finding(s)")
        return 1 if total else 0
    if not args:
        print(__doc__)
        return 2
    backlog_total = [0, 0]
    for tut, named in tutorial_groups(args):
        t, b = check_tutorial(tut, named, flags)
        total += t
        backlog_total = [backlog_total[0] + b[0], backlog_total[1] + b[1]]
    if "--backlog" in flags:
        print(f"backlog total: {backlog_total[0]} examples, {backlog_total[1]} exercises")
    print(f"{total} finding(s)")
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
